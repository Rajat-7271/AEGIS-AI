def test_report_html_renders_as_pdf_when_weasyprint_available():
    """Smoke-test the same HTML -> WeasyPrint PDF conversion as the API."""
    import pytest

    weasyprint = pytest.importorskip("weasyprint")
    state = InvestigatorState(
        case_id="case-pdf-smoke",
        alert_summary="Suspicious endpoint activity",
        recon={"iocs": [{"type": "domain", "value": "example.invalid"}]},
        forensic={"timeline": [{"ts": "2026-11-08T10:00:00Z", "event": "Suspicious process observed"}]},
    )
    markdown_report = render_incident_report_md(state)
    assert "threat-intelligence evidence.\n\n- No actor hypothesis was returned." in markdown_report
    rendered = _md_to_html(markdown_report, state.case_id)
    assert "AEGIS AI Incident Report" in rendered
    assert "Generated by AEGIS AI on" in rendered
    assert "li { margin: 0.3em 0; line-height: 1.35; }" in rendered
    pdf_bytes = weasyprint.HTML(string=rendered).write_pdf()
    assert pdf_bytes.startswith(b"%PDF-")
    assert len(pdf_bytes) > 1000
    import os
    from pathlib import Path

    output = os.environ.get("AEGIS_PDF_SMOKE_OUTPUT")
    if output:
        destination = Path(output)
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(pdf_bytes)

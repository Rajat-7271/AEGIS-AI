"""Evidence-first executive summary regression tests."""
from app.investigator.report_writer_agent import _md_to_html, render_incident_report_md
from app.investigator.state import InvestigatorState


def _summary(report: str) -> str:
    return report.split("## Executive Summary\n", 1)[1].split("## Timeline of Events", 1)[0]


def test_sparse_report_does_not_invent_findings():
    state = InvestigatorState(case_id="case-sparse", alert_summary="")
    summary = _summary(render_incident_report_md(state))
    assert "No validated indicators of compromise were returned." in summary
    assert "No valid ATT&CK technique IDs were returned." in summary
    assert "No timeline events were returned." in summary
    assert "no response action was executed" in summary
    assert "No forensic assessment was returned." in summary


def test_summary_uses_structured_findings_and_qualifies_hypotheses():
    state = InvestigatorState(
        case_id="case-123",
        alert_summary="Suspicious login",
        recon={"iocs": [{"type": "ip", "value": "192.0.2.1"}], "mitre_techniques": ["T1078"]},
        forensic={"timeline": [{"ts": "2026-01-01", "event": "Login observed", "src": "EDR"}], "summary": "Possible credential misuse"},
    )
    summary = _summary(render_incident_report_md(state))
    assert "Suspicious login" in summary
    assert "1 structured entries returned (not independently validated)" in summary
    assert "1 automated entries" in summary
    assert "1 candidate technique IDs" in summary
    assert "Forensic assessment (automated hypothesis):** Possible credential misuse" in summary
    assert summary == _summary(render_incident_report_md(state))
    assert "- **Indicators:**" in summary
    assert "- **Response status:**" in summary


def test_untrusted_alert_text_is_escaped_and_summary_is_not_workflow_dump():
    state = InvestigatorState(
        case_id="case-x",
        alert_summary="<script>alert(1)</script>",
    )
    summary = _summary(render_incident_report_md(state))
    assert "<script>" not in summary
    assert "&lt;script&gt;" in summary
    assert "case creation workflow" not in summary.lower()


def test_unconfirmed_actor_is_not_presented_as_certain_in_rationale():
    state = InvestigatorState(
        case_id="case-attribution",
        recon={"threat_actors": ["APT28"]},
        responder={"recommended_actions": [
            {"action": "Preserve endpoint telemetry", "rationale": "APT28 is responsible for this incident"}
        ]},
    )
    report = render_incident_report_md(state)
    assert "Rationale withheld: unconfirmed threat-actor attribution." in report
    assert "APT28 is responsible" not in report
    assert "Unconfirmed model-generated leads: APT28" in report


def test_pdf_html_uses_aegis_branding_not_legacy_aisoc():
    rendered = _md_to_html("# Incident Report", "case-123")
    assert "<title>AEGIS AI Incident Report" in rendered
    assert "Generated by AEGIS AI on" in rendered
    assert "AiSOC" not in rendered


def test_unverified_ioc_blocking_proposals_are_withheld():
    state = InvestigatorState(
        case_id="case-no-iocs",
        responder={
            "containment_steps": ["Block the document hash and associated IOCs at the gateway"],
            "recommended_actions": [
                {"action": "Block identified C2 IPs/domains at perimeter firewall", "rationale": "Stop C2"}
            ],
        },
    )
    report = render_incident_report_md(state)
    assert report.count("An indicator-blocking proposal was withheld") == 2
    assert "Block the document hash and associated IOCs" not in report
    assert "Block identified C2 IPs/domains" not in report


